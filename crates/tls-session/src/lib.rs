//! Полноценный TLS-handshake для проверок, которым мало открытой части.
//!
//! Назначение: key schedule TLS 1.3 (расшифровка EncryptedExtensions,
//! Certificate, CertificateVerify, Finished) и полный handshake TLS 1.0–1.2
//! на примитивах RustCrypto (вариант C, ARCHITECTURE.md, раздел 3.5).
//!
//! Границы ответственности: wire-формат берётся из `tls-probe`; крейт не
//! зависит от `net` и сам соединений не открывает. Это не TLS-клиент общего
//! назначения: набор suites минимален и рассчитан на нужды сканера.
//!
//! Feature `openssl-fallback` объявлена как запасной путь и по умолчанию
//! выключена; реализации за ней пока нет.
//!
//! Состояние: скелет Фазы 0. Наполнение начинается с задачи P1-21.
